TEMPLATE = """
## 🎮 加练任务包

> 下面这些题目不一定比章末题更难，但更适合“多刷几遍、把手感练出来”。建议先独立做，再展开提示。

{items}

---

"""

ITEM_TEMPLATE = """### 加练 {num} · {title} {level}

{prompt}

<details>
<summary>💡 提示 / 答案要点</summary>

{answer}

</details>

---
"""


def make_section(items):
    body = "\n".join(ITEM_TEMPLATE.format(num=n, level=level, title=title, prompt=prompt, answer=answer) for n, level, title, prompt, answer in items)
    return TEMPLATE.format(items=body)


def main():
    changed = 0
    skipped = 0
    failed = []
    for rel, items in EXTRAS.items():
        path = ROOT / rel
        text = path.read_text(encoding="utf-8")
        if "## 🎮 加练任务包" in text:
            skipped += 1
            continue
        anchor = "## Practice Problems"
        if anchor not in text:
            failed.append((rel, "missing Practice Problems"))
            continue
        section = make_section(items)
        text = text.replace(anchor, section + anchor, 1)
        path.write_text(text, encoding="utf-8")
        changed += 1
    print(f"changed={changed} skipped={skipped} failed={len(failed)}")
    for item in failed:
        print("FAILED", item[0], item[1])
    if failed:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
